const norm = (s) => String(s || "").replace(/[\s（）()]/g, "").toLowerCase();
const INDEX = FOODS.flatMap((f) => f.n.map((name) => [norm(name), f.v])).sort((a, b) => b[0].length - a[0].length);

// Exact name match first, then the longest table name the item's name ends with ("清炒西兰花" → 西兰花).
// Mixed dishes ("西兰花炒牛肉") don't end with one food, so they keep the model's numbers.
export function lookupFood(name) {
  const s = norm(name);
  if (!s) return null;
  const hit = INDEX.find(([k]) => k === s) || INDEX.find(([k]) => k.length >= 2 && s.endsWith(k) && s.length - k.length <= 2);
  return hit ? { kcal: hit[1][0], p: hit[1][1], c: hit[1][2], f: hit[1][3] } : null;
}
